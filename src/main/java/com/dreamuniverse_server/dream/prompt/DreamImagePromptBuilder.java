
package com.dreamuniverse_server.dream.prompt;

import org.springframework.stereotype.Component;

@Component
public class DreamImagePromptBuilder {

    private static final String COMMON_RULES = """
            [공통 안전 규칙]
            - 꿈의 원래 사건 흐름과 분위기를 가능한 한 충실하게 유지한다.
            - 등장인물의 외형과 복장은 모든 패널에서 일관되게 유지한다.
            - 모든 등장인물은 연령에 적절하고 비선정적인 방식으로 표현한다.
            - 민감하거나 부적절한 장면은 직접적이지 않고 상징적이며 안전한 방식으로 완화한다.
            - 폭력적인 장면은 비그래픽하게 표현한다.
            - 자해, 학대, 위험한 상황은 미화하지 않고 안전한 방식으로 표현한다.
            """;

    private static final String MINOR_RULES = """
            [미성년 사용자 추가 규칙]
            - 모든 인물과 장면은 연령에 적절한 방식으로 표현한다.
            - 선정적이거나 부적절한 표현은 사용하지 않는다.
            - 위험하거나 폭력적인 장면은 강도를 낮추고 비그래픽하게 표현한다.
            """;

    private static final String ADULT_RULES = """
            [성인 사용자 규칙]
            - 안전 규칙을 지키는 범위 안에서 꿈의 분위기와 내용을 가능한 한 충실하게 표현한다.
            - 공포, 불안, 로맨스, 긴장감 같은 감정적 분위기는 꿈의 원래 느낌을 유지한다.
            """;

    private static final String CHARACTER_RULES = """
            [캐릭터 일관성 규칙]
            - 같은 인물은 이미지의 처음부터 마지막 패널까지 동일한 사람으로 표현한다.
            - 특히 꿈의 주인공은 모든 패널에서 동일한 인물이어야 한다.
            - 주인공의 성별 표현, 나이대, 얼굴 특징, 머리 모양, 머리 색, 체형, 복장은 패널 사이에서 변경하지 않는다.
            - 장면이나 장소가 바뀌더라도 주인공이 다른 사람처럼 보이면 안 된다.
            - 꿈 원문에 외형 정보가 없다면 하나의 자연스러운 대표 외형을 정한 뒤 모든 패널에서 유지한다.
            - 다른 등장인물과 주인공이 혼동되지 않도록 명확하게 구분한다.
            """;

    private static final String DREAM_SEQUENCE_RULES = """
            [최우선 규칙: 꿈의 시간 순서]
            - 꿈 원문의 첫 번째 사건부터 시작하여 작성된 순서대로 시각화한다.
            - 꿈의 장면을 앞에서부터 하나씩 차례대로 표현한다.
            - 꿈 전체를 요약하거나 핵심 장면만 추출하지 않는다.
            - 뒤쪽의 중요한 사건을 표현하기 위해 앞쪽 사건을 건너뛰지 않는다.
            - 꿈의 마지막 장면이나 결말을 우선적으로 선택하지 않는다.
            - 앞부분부터 순서대로 그리다가 이미지 공간이 부족하면 이후 사건은 표현하지 않는다.
            - 표현하지 못한 뒷부분을 마지막 패널에 억지로 압축하지 않는다.
            - 서로 다른 시간대나 장소를 하나의 패널에 억지로 합치지 않는다.
            - 원문에 존재하지 않는 사건이나 등장인물을 추가하지 않는다.
            - 꿈의 사건 순서를 바꾸지 않는다.
            - 꿈의 끝까지 표현하지 못하더라도 앞부분의 순차적인 흐름을 유지한다.
            """;

    private static final String LAYOUT_READABILITY_RULES = """
            [최우선 규칙: 패널 가독성과 크기 균형]
            - 전체 이미지는 읽기 쉬운 하나의 컬러 만화 페이지로 구성한다.
            - 각 패널은 스마트폰 화면에서도 인물의 표정과 핵심 행동을 식별할 수 있을 만큼 충분히 커야 한다.
            - 모든 패널은 가능한 한 비슷한 크기로 구성한다.
            - 특정 패널만 다른 패널에 비해 지나치게 작거나 좁아지지 않도록 한다.
            - 매우 작거나 가늘고 긴 패널을 만들지 않는다.
            - 지나치게 작은 보조 패널, 삽입 컷, 썸네일 형태의 패널을 추가하지 않는다.
            - 하나의 패널 내부를 여러 개의 작은 패널로 다시 분할하지 않는다.
            - 장면을 더 많이 표현하기 위해 패널 크기나 가독성을 희생하지 않는다.
            - 한 패널에는 하나의 주요 시간적 순간을 명확하게 표현한다.
            - 패널 사이의 경계는 명확하게 구분한다.
            - 복잡한 콜라주나 과밀한 스토리보드처럼 구성하지 않는다.
            - 추가 장면을 넣으면 패널이 너무 작아지는 경우, 장면 추가를 중단한다.
            - 패널 개수를 늘리는 것보다 개별 패널의 가독성을 우선한다.
            """;

    private static final String IMAGE_STYLE_RULES = """
            [이미지 스타일]
            - 현실적인 사진이 아니라 완성도 높은 컬러 만화 또는 웹툰 스타일로 표현한다.
            - 장면마다 분위기와 감정이 자연스럽게 전달되도록 한다.
            - 인물의 표정, 행동, 배경이 명확하게 보이도록 한다.
            - 패널 사이의 시간 흐름이 쉽게 이해되어야 한다.
            - 장면을 설명하기 위한 임의의 자막, 제목, 워터마크, 로고는 넣지 않는다.
            - 꿈 원문에 실제 대사가 존재하는 경우에만 말풍선을 사용할 수 있다.
            - 원문에 없는 새로운 대사를 만들어내지 않는다.
            """;

    public String build(
            String dreamContent,
            boolean adult,
            int panelCount
    ) {
        String ageRules =
                adult
                        ? ADULT_RULES
                        : MINOR_RULES;

        String cartoonRules =
                createCartoonRules(panelCount);

        return """
                사용자가 작성한 꿈을 바탕으로 하나의 완성된 컬러 만화 이미지를 생성한다.

                반드시 아래 규칙을 우선순위에 따라 적용한다.

                1. 꿈의 처음부터 시간 순서대로 표현한다.
                2. 모든 패널의 크기와 가독성을 충분히 확보한다.
                3. 이미지 공간이 부족하면 꿈의 뒷부분을 생략한다.
                4. 지정된 이용 정책에 맞게 만화 페이지를 구성한다.
                5. 캐릭터 일관성, 이미지 스타일 및 안전 규칙을 준수한다.

                %s

                %s

                %s

                %s

                %s

                %s

                %s

                [꿈 원문]
                %s
                """.formatted(
                COMMON_RULES,
                ageRules,
                CHARACTER_RULES,
                DREAM_SEQUENCE_RULES,
                LAYOUT_READABILITY_RULES,
                cartoonRules,
                IMAGE_STYLE_RULES,
                dreamContent
        );
    }

    private String createCartoonRules(int panelCount) {

        if (panelCount == 4) {
            return """
                    [무료 사용자: 정사각형 만화 구성]
                    - 정사각형 이미지 안에 최소 4개의 주요 패널을 표현하는 것을 목표로 한다.
                    - 기본적으로 2열 x 2행 구성을 우선한다.
                    - 꿈의 첫 번째 사건부터 시간 순서대로 장면을 배치한다.
                    - 짧은 꿈은 약 4개의 패널로 자연스럽게 표현한다.
                    - 짧은 꿈에서 장면 수를 채우기 위해 원문에 없는 사건을 만들거나 동일한 사건을 불필요하게 반복하지 않는다.
                    - 긴 꿈이라도 전체 내용을 압축하거나 요약하지 않는다.
                    - 긴 꿈은 처음부터 순서대로 표현하다가 공간이 부족하면 뒷부분을 생략한다.
                    - 뒤쪽 사건을 표현하기 위해 앞쪽 사건을 건너뛰지 않는다.
                    - 더 많은 장면을 표현하기 위해 작은 패널을 추가하지 않는다.
                    - 패널 크기 균형과 가독성을 컷 수보다 우선한다.
                    """;
        }

        if (panelCount == 8) {
            return """
                    [프리미엄 사용자: 세로형 확장 만화 구성]
                    - 세로로 긴 이미지 공간을 활용하여 꿈을 표현한다.
                    - 꿈의 길이와 사건 진행에 따라 패널 개수를 유연하게 결정한다.
                    - 반드시 8개의 패널을 채울 필요는 없다.
                    - 짧은 꿈은 4~6개 정도의 충분히 큰 패널로 표현할 수 있다.
                    - 긴 꿈은 6~8개 정도의 패널 구성을 우선 고려한다.
                    - 위 숫자는 목표나 참고 기준이며, 고정된 패널 개수는 아니다.
                    - 모든 패널은 충분히 크게 표현하고 전체적으로 비슷한 크기를 유지한다.
                    - 세로형 공간에 무리하게 많은 패널을 배치하지 않는다.
                    - 꿈의 첫 번째 사건부터 원문 순서대로 표현한다.
                    - 무료 사용자보다 넓은 이미지 공간을 활용해 꿈의 더 뒷부분까지 순차적으로 표현한다.
                    - 긴 꿈이라도 전체 사건을 요약하거나 중간 사건을 건너뛰지 않는다.
                    - 이미지 공간이 부족하면 이후의 사건을 생략한다.
                    - 짧은 꿈은 장면 수를 억지로 늘리거나 동일한 사건을 반복하지 않는다.
                    - 패널 개수보다 장면의 가독성과 크기 균형을 우선한다.
                    """;
        }

        throw new IllegalArgumentException(
                "Unsupported panel count: " + panelCount
        );
    }
}
